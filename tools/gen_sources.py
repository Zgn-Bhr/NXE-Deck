#!/usr/bin/env python3
"""Generate options/sources.css: which capsules are Heroic, Retro or App shortcuts.

Case bands "By source" labels every capsule STEAM unless this file says otherwise.
A capsule only exposes its artwork address, and non-Steam shortcuts and Steam games
with custom (SteamGridDB) art both use /customimages/<id>p.png, so the shortcut IDs
have to come from Steam's own list: ~/.local/share/Steam/userdata/<user>/config/
shortcuts.vdf on the Deck. Each shortcut is classified by its launch command.

    # on the Deck itself (Desktop Mode, Konsole): straight into the installed theme
    python3 gen_sources.py --out ~/homebrew/themes/"NXE Deck"/options/sources.css
    DECK=deck@<ip> python3 tools/gen_sources.py --out FILE  # from another machine over SSH (deploy.sh)
    python3 tools/gen_sources.py --vdf shortcuts.vdf --out FILE
    python3 tools/gen_sources.py --empty               # the neutral file shipped in the theme

The theme ships a neutral options/sources.css (no shortcut IDs): published copies
carry nobody's library. tools/deploy.sh generates the personal one into a temporary
file and copies it straight onto the Deck. Only numeric IDs and categories are
written; no game names or paths. Re-run (or redeploy) after adding non-Steam games.
"""

import argparse
import os
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "NXE Deck" / "options" / "sources.css"

# Checked in order against the shortcut's Exe + LaunchOptions + StartDir (lower case).
RULES = [
    ("heroic", ["heroic"]),
    ("retro", ["emulation/", "emudeck", "retroarch", "launchers/", "es-de", "esde", "pegasus",
               "steam-rom-manager", "rgsx", "yuzu", "ryujinx", "dolphin", "pcsx2", "rpcs3", "cemu",
               "duckstation", "ppsspp", "citra", "melonds", "xemu", "primehack", "mame", "scummvm",
               "vita3k", "xenia", "flycast", "mgba", "snes9x", "azahar", "shadps4"]),
]
DEFAULT = "app"


def parse_vdf(b, i=0):
    obj = {}
    while True:
        t = b[i]
        i += 1
        if t == 8:
            return obj, i
        j = b.index(0, i)
        key = b[i:j].decode("utf-8", "replace")
        i = j + 1
        if t == 0:
            val, i = parse_vdf(b, i)
        elif t == 1:
            j = b.index(0, i)
            val = b[i:j].decode("utf-8", "replace")
            i = j + 1
        elif t == 2:
            val = struct.unpack("<i", b[i:i + 4])[0]
            i += 4
        else:
            raise ValueError(f"unknown VDF type {t}")
        obj[key] = val


def fetch_vdf(deck):
    # The most recently written shortcuts.vdf (one per Steam account on the Deck).
    path = subprocess.run(
        ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=8", deck,
         "ls -t ~/.local/share/Steam/userdata/*/config/shortcuts.vdf 2>/dev/null | head -1"],
        capture_output=True, text=True, check=True).stdout.strip()
    if not path:
        return None
    tmp = Path(tempfile.mkdtemp()) / "shortcuts.vdf"
    subprocess.run(["scp", "-q", f"{deck}:{path}", str(tmp)], check=True)
    return tmp.read_bytes()


def local_vdf():
    # Running on the Deck: the most recently written local shortcuts.vdf.
    paths = sorted(Path.home().glob(".local/share/Steam/userdata/*/config/shortcuts.vdf"),
                   key=lambda p: p.stat().st_mtime, reverse=True)
    return paths[0].read_bytes() if paths else None


def classify(s):
    blob = " ".join(str(s.get(k, "")) for k in ("Exe", "exe", "LaunchOptions", "StartDir")).lower()
    for cat, needles in RULES:
        if any(n in blob for n in needles):
            return cat
    return DEFAULT


def css(groups):
    lines = [
        "/* NXE Deck option: Case bands \"By source\", per-shortcut part.",
        "   GENERATED by tools/gen_sources.py from the Deck's shortcuts.vdf; re-run (or",
        "   redeploy) after adding non-Steam games. Numeric shortcut IDs only.",
        "   Labels and colours per category are in options/bands-source.css. */",
        "",
    ]
    scope = ":is(.gamepadhome_ScrollArea, .gamepadlibrary_GamepadLibrary) .appportrait_LibraryItemBox"
    for cat in ("heroic", "retro", "app"):
        ids = sorted(groups.get(cat, []))
        if not ids:
            continue
        sel = ",\n".join(f'{scope}:has(img[src*="/customimages/{i}p."], img[src*="/customimages/{i}."])' for i in ids)
        lines += [f"/* {cat}: {len(ids)} */", sel + " {",
                  f"  --nxe-band-label: var(--nxe-band-{cat}-label);",
                  f"  --nxe-band-color: var(--nxe-band-{cat}-color);",
                  f"  --nxe-band-ink: var(--nxe-band-{cat}-ink);", "}", ""]
    if len(lines) == 5:
        lines.append("/* No shortcut IDs: the copy shipped in the theme. Every cover reads STEAM, and")
        lines.append("   non-Steam shortcuts without artwork read APP. To label your own Heroic, emulator")
        lines.append("   and app shortcuts, run tools/gen_sources.py (see README, \"Case bands by source\"). */")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vdf", help="a copy of shortcuts.vdf (default: $DECK over SSH, else this machine's Steam)")
    ap.add_argument("--out", help=f"output file (required, except with --empty: {OUT.relative_to(ROOT)})")
    ap.add_argument("--empty", action="store_true", help="write the neutral file shipped in the theme")
    args = ap.parse_args()
    if not (args.out or args.empty):
        # The project's own copy stays neutral: it's what gets published.
        ap.error("pass --out FILE (e.g. the installed theme's options/sources.css)")
    out = Path(args.out).expanduser() if args.out else OUT
    if args.empty:
        out.write_text(css({}))
        print("sources: none (neutral) ->", out)
        return
    if args.vdf:
        data = Path(args.vdf).read_bytes()
    elif os.environ.get("DECK"):
        data = fetch_vdf(os.environ["DECK"])
    elif (Path.home() / ".local/share/Steam/userdata").is_dir():
        data = local_vdf()
    else:
        sys.exit("no Steam here: run this on the Deck, set DECK=deck@<ip>, or pass --vdf")
    groups = {}
    if data:
        root, _ = parse_vdf(data)
        for s in root.get("shortcuts", {}).values():
            groups.setdefault(classify(s), []).append(s["appid"] & 0xFFFFFFFF)
    out.write_text(css(groups))
    print("sources:", ", ".join(f"{k} {len(v)}" for k, v in sorted(groups.items())) or "none", "->", out)


if __name__ == "__main__":
    main()
