#!/usr/bin/env python3
"""Generate NXE Deck/options/scroll.css ("NXE scrolling": focused game left-most).

Steam's home carousel (Kr.Xd over ReactVirtualized, read from the client code):
- column width = item width + 12px gap; the last column also gets the grid's
  right padding, which Steam reads from CSS when the carousel mounts;
- focusing column k scrolls to clamp(offset_k - (C - width_k) / 2, 0, total - C),
  C = carousel width (the full screen, 100vw), over 120ms ("sine"), and only when
  that scroll completes does the focus move to column k.

Layout model this file keeps (and options/depth.css relies on): the focused column
always sits centred in the carousel's layout, and one constant transform,
(width - C) / 2, draws everything shifted so it appears at the left edge.
- Steady state, Steam's own scroll centres it.
- Near the start Steam can't scroll below 0, so every column gets margin-left
  max(0, C/2 - width/2 - offset) to centre it instead. Margin, unlike a transform,
  is seen by scroll-driven view timelines, so the depth and fade (which follow each
  column's position) move together with it.
Columns left of the focused one fade out as they slide past it, driven by the same
view timeline, so the fade runs during Steam's scroll rather than after it.

Column widths are px (Steam sizes capsules in px): portrait 134 + 12 = 146px,
featured 430 + 12 = 442px. R (90vw) is the last column's extra right padding,
enough for Steam to centre even the last game.

Usage: python3 tools/gen_scroll.py
"""

from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "NXE Deck" / "options" / "scroll.css"
GRID = ".gamepadhomerecentgames_RecentGamesInnerContainer .ReactVirtualized__Grid__innerScrollContainer"
# The focused column. Steam puts .gpfocuswithin on every nav container around the
# focused element, the carousel cell included. `:has()` can't be nested inside
# another `:has()` (the inner one is silently dropped), so selectors that already
# sit inside a `:has(...)` use the class form only.
FOCUSED = ":is(.gpfocus, .gpfocuswithin, :has(.gpfocus))"
FOCUSED_IN_HAS = ":is(.gpfocus, .gpfocuswithin)"
# Extra right padding for the last column: >= carousel width - column width, so
# Steam can centre the last game, but small enough that the grid box doesn't grow.
R = "90vw"

COL = "var(--nxe-col-w, 146px)"
FEATURED = "var(--nxe-featured-w, 442px)"
SEP = 22  # running-game separator column: 10px + 12px gap
SINE = "cubic-bezier(0.37, 0, 0.63, 1)"  # Steam's "sine" scroll timing, 120ms
# On its view timeline the focused column sits at "cover 50%" less the carousel's
# left padding (2.8vw): Steam centres columns ignoring that padding.
CENTRE = "50% - 2.8vw"

# Start-region margins: (layout condition on GRID, [(nth-child of the focused
# column, its width, its offset)]). Past these Steam's own scroll centres it.
LAYOUTS = {
    "featured (wide) first capsule": (
        ":has(.basicgamecarousel_Featured)",
        [(1, FEATURED, "0px"), (2, COL, FEATURED), (3, COL, f"{FEATURED} + {COL}")],
    ),
    "plain list": (
        ":not(:has(.basicgamecarousel_Featured, .basicgamecarousel_FeaturedSeparator))",
        [(n, COL, f"{n - 1} * {COL}" if n > 1 else "0px") for n in range(1, 7)],
    ),
    "running game (10px separator column + 12px gap after it)": (
        ":has(.basicgamecarousel_FeaturedSeparator):not(:has(.basicgamecarousel_Featured))",
        [(1, COL, "0px")] + [(n, COL, f"{n - 2} * {COL} + {SEP}px") for n in range(3, 8)],
    ),
}


def margin_rule(sel, width, offset):
    return [
        f"{sel} > * {{",
        f"  margin-left: max(0px, 50vw - {width} / 2 - ({offset}));",
        "}",
        "",
    ]


def main():
    lines = [
        '/* NXE Deck option: NXE scrolling. "NXE scrolling" checkbox, on by default.',
        "   GENERATED by tools/gen_scroll.py; edit the generator, not this file.",
        "   The focused game is always the left-most one and games before it slide off",
        "   to the left, like the NXE blades. Steam centres the focused column; this",
        "   keeps it centred in layout (margins where Steam can't scroll) and draws",
        "   everything shifted left by one constant transform (see the generator). */",
        "",
        "/* Steam adds this to the last column's width (read at mount), which lets it",
        "   centre even the last game. */",
        ".gamepadhome_ScrollArea .gamepadhomerecentgames_RecentGamesInnerContainer .basicgamecarousel_BasicGameCarousel {",
        f"  padding-right: {R} !important;",
        "}",
        "",
        "/* Each column is the subject of its own view timeline (its position in the",
        "   carousel); options/depth.css uses it too. The start-region margin moves",
        "   with Steam's scroll timing. */",
        f"{GRID} > * {{",
        "  view-timeline: --nxe-col inline;",
        f"  transition: margin-left 0.12s {SINE}, transform 0.25s ease-out;",
        "}",
        "",
        "/* Games before the focused one fade as they slide past it: over the column",
        "   width left of the centre, while Steam scrolls. depth.css folds this into its",
        "   own column animation (--nxe-fade-to). */",
        f"{GRID} {{",
        "  --nxe-fade-to: 0;",
        "}",
        "",
        f"{GRID}:has(.gpfocus) > * {{",
        "  animation: nxe-col-fade linear both;",
        "  animation-timeline: --nxe-col;",
        f"  animation-range: cover calc({CENTRE}) cover calc({CENTRE} + {COL});",
        "}",
        "",
        "/* The last column is wider by R, which moves its centre R/2 right of its tile;",
        "   focused, Steam centres the whole padded column. */",
        f"{GRID}:has(.gpfocus) > :last-child:not({FOCUSED}) {{",
        f"  animation-range: cover calc({CENTRE} - {R} / 2) cover calc({CENTRE} - {R} / 2 + {COL});",
        "}",
        "",
        "@keyframes nxe-col-fade {",
        "  from { opacity: 1; }",
        "  to { opacity: var(--nxe-fade-to, 0); }",
        "}",
        "",
        "/* The label under the focused game starts at the left now: give it the full width. */",
        ".gamepadhomerecentgames_RecentGamesInnerContainer .basicgamecarousel_CarouselGameLabelWrapper {",
        "  width: calc(100vw - 5.6vw) !important;",
        "}",
        "",
        "/* Draw the centred focused column at the left edge: shift by (C - U)/2. */",
        f"{GRID}:has(.gpfocus) > :not(:last-child) {{",
        "  transform: translateX(calc(50% - 50vw));",
        "}",
        "",
        f"{GRID}:has(.gpfocus) > :last-child {{",
        f"  transform: translateX(calc(50% - 50vw - {R} / 2));",
        "}",
        "",
        "/* The last column focused: Steam centred its whole (padded) width. */",
        f"{GRID} > :last-child{FOCUSED} {{",
        "  transform: translateX(calc(50% - 50vw));",
        "}",
        "",
        "/* Near the start Steam can't scroll below 0: centre the focused column with a",
        "   margin on every column instead, max(0, C/2 - width/2 - offset). */",
        "",
    ]
    for name, (cond, cols) in LAYOUTS.items():
        lines.append(f"/* {name} */")
        for nth, width, off in cols:
            lines += margin_rule(f"{GRID}{cond}:has(> :nth-child({nth}){FOCUSED_IN_HAS})", width, off)
    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parent.parent.parent)} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
