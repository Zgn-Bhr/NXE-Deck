#!/usr/bin/env python3
"""Generate NXE Deck/options/depth.css (spec B.5, carousel shrink-by-distance).

Capsules after the focused one shrink with distance (SCALES) and rise slightly,
abutting with a small overlap (origin left-centre; translateX(-n * 100%) removes n
capsule-widths of shrinkage, and each step also removes Steam's 12px gap + 3px).

Why scroll-driven: Steam's carousel scrolls first (120ms) and only moves the focus
when the scroll completes, so depth keyed on the focus always ran after the slide
(the "X then Z" stutter). Here each capsule's depth is a function of its column's
position in the carousel (a view timeline, --nxe-col), so it changes frame by frame
with Steam's scroll and with the start-region margin of options/scroll.css. The
focused column always sits at the layout centre (Steam's scroll, or scroll.css's
margin), at "cover 50%" of its own timeline less the carousel's 2.8vw left
padding (Steam centres ignoring it); k columns to its right is
k * column-width of scroll before that.

Keyframes run from k = MAX_K + 1 (hidden: past the last step cells would pile up)
through k = MAX_K .. 1 (the steps) to k = 0 (front) and k = -1 (left of the focus,
faded out by --nxe-fade-to when NXE scrolling is on). Columns are stacked
front-to-back with z-index on the same timeline.

While nothing in the carousel is focused (focus is in the tabs below) the old
focus-anchored rules keep the blade's depth, anchored on the featured capsule.

Usage: python3 tools/gen_depth.py
"""

from pathlib import Path

SCALES = [0.86, 0.76, 0.68, 0.62, 0.58, 0.55, 0.55, 0.55]  # spec B.5, then held
MAX_K = len(SCALES)
SPAN = MAX_K + 2  # columns covered by the timeline range: k = MAX_K + 1 .. -1

OUT = Path(__file__).resolve().parent.parent / "NXE Deck" / "options" / "depth.css"
GRID = ".gamepadhomerecentgames_RecentGamesInnerContainer .ReactVirtualized__Grid__innerScrollContainer"
MEDIA = ".basicgamecarousel_BasicGameCarouselItemMediaContainer"
FOCUSED = ":is(.gpfocus, .gpfocuswithin, :has(.gpfocus))"
COL = "var(--nxe-col-w, 146px)"
R = "90vw"  # the last column's extra right padding (scroll.css)
# Steam centres columns ignoring the carousel's left padding (basicgamecarousel
# padding: 2.8vw), so the focused column sits that far right of the true centre.
CENTRE = "50% - 2.8vw"
FEATURED_ANCHOR = f"{GRID}:not(:has(.gpfocus)) > :has(.basicgamecarousel_Featured)"


def step_transform(k, cum):
    if k == 0:
        return "translate(0px, 0px) scale(1)"
    s = SCALES[min(k, MAX_K) - 1]
    return (f"translate(calc({-cum:.3f} * 100% - {k} * var(--nxe-depth-gap, 15px)),"
            f" calc({k} * var(--nxe-depth-rise, -5px))) scale({s})")


def ranges(sel_all, sel_last):
    """Timeline range for portrait columns, and for the wider last column."""
    return [
        f"{sel_all} {{",
        f"  animation-range: cover calc({CENTRE} - {MAX_K + 1} * {COL}) cover calc({CENTRE} + {COL});",
        "}",
        "",
        f"{sel_last} {{",
        f"  animation-range: cover calc({CENTRE} - {R} / 2 - {MAX_K + 1} * {COL}) cover calc({CENTRE} - {R} / 2 + {COL});",
        "}",
        "",
    ]


def main():
    pct = lambda k: f"{(MAX_K + 1 - k) / SPAN * 100:.3f}%"
    cums, cum = {}, 0.0
    for k in range(1, MAX_K + 1):
        cums[k] = cum
        cum += 1 - SCALES[k - 1]

    lines = [
        "/* NXE Deck option: carousel depth (spec B.5). \"Carousel depth\" checkbox, on by default.",
        "   GENERATED by tools/gen_depth.py; edit the generator, not this file.",
        "   Capsules after the focused one shrink with distance (.86 .76 .68 .62 .58 .55)",
        "   and rise slightly, abutting with a small overlap, so the blade recedes like",
        "   the NXE. Scroll-driven: each capsule follows its column's position, so the",
        "   depth moves together with the carousel's scroll (see the generator). */",
        "",
        "/* Each column's view timeline (also declared by scroll.css; repeated here so",
        "   depth works with NXE scrolling off). */",
        f"{GRID} > * {{",
        "  view-timeline: --nxe-col inline;",
        "}",
        "",
        f"{GRID} > * {MEDIA} {{",
        "  transform-origin: left center;",
        "}",
        "",
        "/* \"Go to Library\" is 201px tall where a game's box is 253px (capsule + 52px",
        "   label strip, Steam's LabelHeight): pivot it at the games' centre height, or",
        "   it shrinks around a point 26px higher and sits above the line of capsules. */",
        f"{GRID} > * {MEDIA}.basicgamecarousel_TextBoxCarouselContents {{",
        "  transform-origin: left calc(50% + 26px);",
        "}",
        "",
        "/* While the carousel has focus: depth, fade and stacking from the timeline. */",
        f"{GRID}:has(.gpfocus) > * {{",
        "  animation: nxe-col-depth linear both;",
        "  animation-timeline: --nxe-col;",
        "}",
        "",
        f"{GRID}:has(.gpfocus) > * {MEDIA} {{",
        "  animation: nxe-capsule-depth linear both;",
        "  animation-timeline: --nxe-col;",
        "}",
        "",
    ]
    lines += ranges(f"{GRID}:has(.gpfocus) > *, {GRID}:has(.gpfocus) > * {MEDIA}",
                    f"{GRID}:has(.gpfocus) > :last-child:not({FOCUSED}), {GRID}:has(.gpfocus) > :last-child:not({FOCUSED}) {MEDIA}")

    # Column: stacking (front-to-back) and the fade left of the focus.
    lines += ["@keyframes nxe-col-depth {"]
    lines += [f"  {pct(MAX_K + 1)} {{ z-index: 1; opacity: 1; }}"]
    for k in range(MAX_K, 0, -1):
        lines += [f"  {pct(k)} {{ z-index: {MAX_K + 2 - k}; }}"]
    lines += [f"  {pct(0)} {{ z-index: {MAX_K + 2}; opacity: 1; }}",
              f"  {pct(-1)} {{ z-index: {MAX_K + 2}; opacity: var(--nxe-fade-to, 1); }}", "}", ""]

    # Capsule: scale, slide and rise per step; hidden past the last step.
    lines += ["@keyframes nxe-capsule-depth {",
              f"  {pct(MAX_K + 1)} {{ opacity: 0; transform: {step_transform(MAX_K, cums[MAX_K])}; }}"]
    for k in range(MAX_K, 0, -1):
        lines += [f"  {pct(k)} {{ opacity: 1; transform: {step_transform(k, cums[k])}; }}"]
    lines += [f"  {pct(0)} {{ opacity: 1; transform: {step_transform(0, 0)}; }}",
              f"  {pct(-1)} {{ opacity: 1; transform: {step_transform(0, 0)}; }}", "}", ""]

    # Unfocused carousel: the old static rules, anchored on the featured capsule.
    lines += [
        "/* Focus in the tabs below: keep the blade's depth, anchored on the featured",
        "   capsule (static; the timeline needs the focused column centred). */",
        f"{GRID}:not(:has(.gpfocus)) > * {MEDIA} {{",
        "  transition: transform 0.35s cubic-bezier(0.17, 0.45, 0.14, 0.83);",
        "}",
        "",
        f"{FEATURED_ANCHOR} ~ * {MEDIA} {{",
        "  opacity: 0;",
        "}",
        "",
        f"{FEATURED_ANCHOR} {{",
        f"  z-index: {MAX_K + 2};",
        "}",
        "",
    ]
    for k in range(1, MAX_K + 1):
        sel = FEATURED_ANCHOR + " + *" * k
        lines += [f"{sel} {{", f"  z-index: {MAX_K + 2 - k};", "}", "",
                  f"{sel} {MEDIA} {{", "  opacity: 1;", f"  transform: {step_transform(k, cums[k])};", "}", ""]

    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parent.parent.parent)} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
